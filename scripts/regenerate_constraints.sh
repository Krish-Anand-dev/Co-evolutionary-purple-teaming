#!/usr/bin/env bash
# Regenerate constraints-py312.txt (the full lock) from requirements.txt in a clean Linux container, the same base image
# as the Dockerfile and CI. Run from the repo root after changing requirements.txt, then run the tests (docker build + run).
#   bash scripts/regenerate_constraints.sh
set -euo pipefail
cd "$(dirname "$0")/.."

MSYS_NO_PATHCONV=1 docker run --rm -v "$PWD:/src" -w /src python:3.12-slim bash -c '
  set -euo pipefail
  python -m venv /tmp/lock
  /tmp/lock/bin/pip install -q --upgrade pip
  /tmp/lock/bin/pip install -q -r requirements.txt
  {
    echo "# Full lock of every package (top-level + transitive) for Python 3.12 on Linux x86_64, generated by '"'"'pip freeze'"'"' after"
    echo "# '"'"'pip install -r requirements.txt'"'"' in python:3.12-slim (the same base as the Dockerfile and CI). Used as a pip CONSTRAINTS file:"
    echo "#   pip install -r requirements.txt -c constraints-py312.txt"
    echo "# Regenerate it (and re-run the tests) whenever requirements.txt changes; see docs/setup.md, section Updating the pins."
    /tmp/lock/bin/pip freeze | sort -f
  } > constraints-py312.txt
'
echo "wrote constraints-py312.txt ($(grep -c '==' constraints-py312.txt) pins)"
